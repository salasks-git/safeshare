let _lang = localStorage.getItem('sd_lang') || 'en';
if (!STRINGS[_lang]) _lang = 'en';

export function getLang() {
  return _lang;
}

export function setLang(l) {
  _lang = STRINGS[l] ? l : 'en';
  localStorage.setItem('sd_lang', _lang);
}

export function t(key, ...args) {
  const dict = STRINGS[_lang] || STRINGS.en;
  const val = dict[key] ?? STRINGS.en[key] ?? key;
  return typeof val === 'function' ? val(...args) : val;
}
